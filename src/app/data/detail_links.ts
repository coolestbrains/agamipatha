function linkCert(name: string, allowFallback = true): LinkedCert | null {
  const n = name.toLowerCase();
  for (const rule of CERT_LINK_RULES) {
    if (rule.test(n)) {
      return { name, coach: rule.coach, url: rule.url };
    }
  }
  if (!allowFallback) {
    return null;
  }
  return { name, coach: 'Official body / recognised training', url: 'https://swayam.gov.in/' };
}

function takeCerts(target: LinkedCert[], extras: LinkedCert[]): LinkedCert[] {
  const seen = new Set<string>();
  const out: LinkedCert[] = [];
  const add = (cert: LinkedCert) => {
    const key = normKey(cert.name);
    if (!key || seen.has(key) || out.length >= LIMIT) {
      return;
    }
    seen.add(key);
    out.push(cert);
  };
  for (const cert of target) {
    add(cert);
  }
  for (const cert of extras) {
    add(cert);
  }
  return out;
}

export function linkedInstitutes(node: LinkNode, siblingInstitutes: string[] = []): LinkedRef[] {
  const own = node.institutes ?? [];
  const pad = node.kind === 'profession' ? [] : siblingInstitutes;
  // Pass names only — mergeNamed resolves URLs up to LIMIT, not for every sibling.
  return mergeNamed(
    own,
    pad.map((name) => ({ name })),
  );
}

export function linkedEmployers(node: LinkNode): LinkedRef[] {
  if (SKIP_EMPLOYER_KINDS.has(node.kind)) {
    return [];
  }
  const byId = EMPLOYERS_BY_ID[node.id];
  if (byId) {
    return byId.slice(0, LIMIT);
  }
  const byField = EMPLOYERS_BY_FIELD[node.field];
  return byField ? byField.slice(0, LIMIT) : [];
}

export function linkedCertifications(node: LinkNode, existing: string[]): LinkedCert[] {
  const fromCatalog = existing
    .map((name) => linkCert(name, true))
    .filter((cert): cert is LinkedCert => !!cert);
  const byId = CERTS_BY_ID[node.id] ?? [];
  const fromExams = (node.exams ?? [])
    .map((name) => linkCert(name, false))
    .filter((cert): cert is LinkedCert => !!cert);
  if (node.kind === 'profession') {
    return takeCerts(fromCatalog, byId);
  }
  if (node.kind === 'school' || node.kind === 'higher-secondary' || node.kind === 'entrance-exam') {
    return takeCerts(fromCatalog, [...byId, ...fromExams]);
  }
  const byField = CERTS_BY_FIELD[node.field] ?? [];
  return takeCerts(fromCatalog, [...byId, ...byField, ...fromExams]);
}

export function urlForInstitute(name: string): string | undefined {
  const n = name.toLowerCase();
  const cached = INSTITUTE_URL_CACHE.get(n);
  if (cached !== undefined) {
    return cached || undefined;
  }
  let best: { len: number; url: string } | undefined;
  for (const [key, url] of INSTITUTE_SITES) {
    if (n.includes(key) && key.length >= (best?.len ?? 0)) {
      best = { len: key.length, url };
    }
  }
  const hit = best?.url ?? '';
  INSTITUTE_URL_CACHE.set(n, hit);
  return hit || undefined;
}

function normKey(name: string): string {
  return name.toLowerCase().replace(/\(.*?\)/g, ' ').replace(/\s+/g, ' ').trim();
}

function mergeNamed(primary: string[], fallback: LinkedRef[], limit = LIMIT): LinkedRef[] {
  const seen = new Set<string>();
  const out: LinkedRef[] = [];
  const add = (name: string, url?: string) => {
    const key = normKey(name);
    if (!key || seen.has(key)) {
      return;
    }
    seen.add(key);
    out.push({ name, url: url || urlForInstitute(name) });
  };
  for (const name of primary) {
    add(name);
    if (out.length >= limit) {
      return out;
    }
  }
  for (const item of fallback) {
    add(item.name, item.url);
    if (out.length >= limit) {
      break;
    }
  }
  return out.slice(0, limit);
}

